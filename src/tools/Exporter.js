import { formatHTML, stripEditorArtifacts, sanitize, dedent } from './Serializer.js';
import StyleManager, { BASE_CSS } from './StyleManager.js';
import { slugify } from './ProjectManager.js';
import { createZip } from './Zip.js';

const ASSET_ATTRIBUTES = [['img', 'src'], ['video', 'src'], ['video', 'poster'], ['audio', 'src'], ['source', 'src']];
const CSS_URL = /url\(\s*(['"]?)([^'")]+)\1\s*\)/g;

export const pageFileName = (page, index) => (index === 0 ? 'index.html' : `${page.slug}.html`);

const pageCSSFileName = (page, index) => (index === 0 ? 'index.css' : `${page.slug}.css`);

/**
 * Collects same-origin assets (builder images…) so they can be bundled with
 * the export instead of pointing back at the builder.
 */
class AssetRegistry {
	constructor() {
		this.byUrl = new Map();
		this.names = new Set();
	}

	/** Returns the bundled file name for a URL, or null when it should stay as is. */
	add(rawUrl) {
		let url;
		try {
			url = new URL(rawUrl, location.href);
		} catch (err) {
			return null;
		}
		if (url.origin !== location.origin || !/^https?:$/.test(url.protocol)) return null;

		const key = url.href;
		if (this.byUrl.has(key)) return this.byUrl.get(key);

		const file = decodeURIComponent(url.pathname.split('/').pop() || 'asset');
		const dot = file.lastIndexOf('.');
		const stem = slugify(dot > 0 ? file.slice(0, dot) : file);
		const ext = dot > 0 ? file.slice(dot).toLowerCase().replace(/[^.a-z0-9]/g, '') : '';
		let name = stem + ext;
		for (let n = 2; this.names.has(name); n++) name = `${stem}-${n}${ext}`;

		this.names.add(name);
		this.byUrl.set(key, name);
		return name;
	}

	async fetchAll() {
		const files = await Promise.all(Array.from(this.byUrl, async ([url, name]) => {
			try {
				const response = await fetch(url);
				if (!response.ok) throw new Error(`HTTP ${response.status}`);
				return { name: `assets/${name}`, data: new Uint8Array(await response.arrayBuffer()) };
			} catch (err) {
				console.warn(`Could not bundle asset ${url}`, err);
				return null;
			}
		}));
		return files.filter(Boolean);
	}
}

function rewriteCSSUrls(css, assets, prefix) {
	if (!assets) return css;
	return css.replace(CSS_URL, (match, quote, url) => {
		const name = assets.add(url.trim());
		return name ? `url("${prefix}${name}")` : match;
	});
}

/**
 * Compile one page into a standalone document.
 * Returns { doc, css, templateCSS }, where css holds the page's generated rules.
 */
function compilePage(page, assets) {
	const doc = document.implementation.createHTMLDocument(page.title || page.name);
	doc.documentElement.lang = 'en';

	const charset = doc.createElement('meta');
	charset.setAttribute('charset', 'UTF-8');
	const viewport = doc.createElement('meta');
	viewport.name = 'viewport';
	viewport.content = 'width=device-width, initial-scale=1';
	doc.head.prepend(charset, viewport);

	const template = doc.createElement('template');
	template.innerHTML = page.html || '';
	sanitize(template.content);
	doc.body.append(template.content);

	// Template stylesheets move into the shared stylesheet.
	const templateCSS = [];
	doc.body.querySelectorAll('style').forEach(style => {
		const css = dedent(style.textContent);
		if (css.trim()) templateCSS.push(css);
		style.remove();
	});

	// Every styled element gets an id the generated rules can target, so ids
	// must be unique: a template added twice repeats its ids. Keep the first.
	const used = new Set();
	doc.querySelectorAll('[id]').forEach(el => {
		if (used.has(el.id)) el.removeAttribute('id');
		else used.add(el.id);
	});
	const counters = {};
	const selectors = {};
	Object.keys(page.styles || {}).forEach(structureId => {
		const el = doc.body.querySelector(`[data-structure-id="${CSS.escape(structureId)}"]`);
		if (!el) return;
		if (!el.id) {
			let label = el.localName;
			try { label = JSON.parse(el.getAttribute('data-buffer') || '{}').label || label; } catch (err) {}
			const base = slugify(label);
			let id;
			do { counters[base] = (counters[base] || 0) + 1; id = `${base}-${counters[base]}`; } while (used.has(id));
			used.add(id);
			el.id = id;
		}
		selectors[structureId] = `#${CSS.escape(el.id)}`;
	});

	const templateWrappers = Array.from(doc.body.querySelectorAll('[data-buffer*="\\"type\\":\\"template\\""]'));
	stripEditorArtifacts(doc.body);

	// Template wrappers only exist for the editor; drop them unless they were styled.
	templateWrappers.forEach(wrapper => {
		if (wrapper.localName === 'div' && !wrapper.attributes.length) wrapper.replaceWith(...wrapper.childNodes);
	});

	if (assets) {
		ASSET_ATTRIBUTES.forEach(([tag, attr]) => {
			doc.body.querySelectorAll(`${tag}[${attr}]`).forEach(el => {
				const name = assets.add(el.getAttribute(attr));
				if (name) el.setAttribute(attr, `assets/${name}`);
			});
		});
	}

	const css = StyleManager.compile(page.styles, id => selectors[id] || null);
	return { doc, css, templateCSS };
}

function sharedStylesheet(templateCSS, siteCSS) {
	const sections = ['/* Generated by Web Builder */', `/* Base */\n${BASE_CSS}`];
	const unique = Array.from(new Set(templateCSS));
	if (unique.length) sections.push(`/* Templates */\n${unique.join('\n\n')}`);
	if (siteCSS.trim()) sections.push(`/* Site */\n${siteCSS.trim()}`);
	return sections.join('\n\n') + '\n';
}

function addStylesheet(doc, href) {
	const link = doc.createElement('link');
	link.rel = 'stylesheet';
	link.href = href;
	doc.head.appendChild(link);
}

/**
 * Build every page of the project as it will be published.
 * @returns {{ files: {name: string, data: string}[], assets: AssetRegistry }}
 */
export function buildSite(projectData, { bundleAssets = true } = {}) {
	const assets = bundleAssets ? new AssetRegistry() : null;
	const templateCSS = [];
	const files = [];

	projectData.pages.forEach((page, index) => {
		const compiled = compilePage(page, assets);
		templateCSS.push(...compiled.templateCSS);

		addStylesheet(compiled.doc, 'css/style.css');
		if (compiled.css) {
			const cssName = pageCSSFileName(page, index);
			addStylesheet(compiled.doc, `css/${cssName}`);
			files.push({
				name: `css/${cssName}`,
				data: `/* ${page.name} */\n${rewriteCSSUrls(compiled.css, assets, '../assets/')}\n`,
			});
		}
		files.unshift({ name: pageFileName(page, index), data: formatHTML(compiled.doc) + '\n' });
	});

	const shared = sharedStylesheet(templateCSS, projectData.siteCSS || '');
	files.push({ name: 'css/style.css', data: rewriteCSSUrls(shared, assets, '../assets/') });

	files.sort((a, b) => Number(a.name.includes('/')) - Number(b.name.includes('/')) || a.name.localeCompare(b.name));
	return { files, assets };
}

/** Bundle the whole site (pages, generated CSS, images) into a ZIP blob. */
export async function exportSiteZip(projectData) {
	const { files, assets } = buildSite(projectData);
	return createZip([...files, ...(await assets.fetchAll())]);
}

/**
 * HTML + CSS for one page as it will be exported (used by the code viewer).
 */
export function buildPageCode(projectData, pageId) {
	const index = projectData.pages.findIndex(p => p.id === pageId);
	const page = projectData.pages[index];
	const compiled = compilePage(page, null);

	addStylesheet(compiled.doc, 'css/style.css');
	if (compiled.css) addStylesheet(compiled.doc, `css/${pageCSSFileName(page, index)}`);

	// style.css is shared: it holds the template CSS of every page, as published.
	const templateCSS = projectData.pages.flatMap(p => (p === page ? compiled : compilePage(p, null)).templateCSS);

	return {
		fileName: pageFileName(page, index),
		html: formatHTML(compiled.doc),
		css: compiled.css,
		sharedCSS: sharedStylesheet(templateCSS, projectData.siteCSS || ''),
	};
}

/**
 * A self-contained document for previewing one page: the generated CSS is
 * inlined and assets keep their absolute builder URLs.
 */
export function buildPreviewHTML(projectData, pageId) {
	const page = projectData.pages.find(p => p.id === pageId);
	const compiled = compilePage(page, null);

	const style = compiled.doc.createElement('style');
	style.textContent = `${sharedStylesheet(compiled.templateCSS, projectData.siteCSS || '')}\n${compiled.css}`;
	compiled.doc.head.appendChild(style);
	return formatHTML(compiled.doc);
}
